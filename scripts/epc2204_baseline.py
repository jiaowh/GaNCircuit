def cross(xs, ys, level, start=0):
    """First linear-interpolated x where ys reaches level (either direction) after index start."""
    for i in range(max(start, 1), len(ys)):
        a, b = ys[i - 1] - level, ys[i] - level
        if a == 0:
            return xs[i - 1]
        if a * b < 0 or b == 0:
            return xs[i - 1] + (xs[i] - xs[i - 1]) * (-a) / (b - a)
    return None


def cumtrapz(xs, ys):
    out = [0.0]
    for i in range(1, len(xs)):
        out.append(out[-1] + 0.5 * (ys[i] + ys[i - 1]) * (xs[i] - xs[i - 1]))
    return out


def at(xs, ys, x):
    for i in range(1, len(xs)):
        if xs[i] >= x:
            return ys[i - 1] + (ys[i] - ys[i - 1]) * (x - xs[i - 1]) / (xs[i] - xs[i - 1])
    return None


def classify(name, value):
    row = dict(DATASHEET[name])
    row["model"] = value
    if value is None:
        row.update(limit_check="not-measured", typical_check="not-measured", review=True)
        return row
    if "min" in row or "max" in row:
        inside = row.get("min", -math.inf) <= value <= row.get("max", math.inf)
        row["limit_check"] = "inside-limits" if inside else "outside-limits"
    else:
        row["limit_check"] = "no-limits"
    if "typ" in row:
        row["deviation_from_typ"] = value / row["typ"] - 1
        row["typical_check"] = ("within-screening-band" if abs(row["deviation_from_typ"]) <= SCREENING_BAND
                                else "outside-screening-band")
    else:
        row["typical_check"] = "no-typical"
    row["review"] = row["limit_check"] == "outside-limits" or row["typical_check"] == "outside-screening-band"
    return row


def subckt_params(lib_text, name="EPC2204"):
    """Evaluate the .param values of one subcircuit in the local vendor library."""
    start = lib_text.index(f".subckt {name} ")
    body = lib_text[start:lib_text.index(".ends", start)]
    lines = []
    for line in body.splitlines():
        if line.startswith("+") and lines:
            lines[-1] += " " + line[1:]
        else:
            lines.append(line)
    raw = {}
    for line in lines:
        if line.lower().startswith(".param"):
            for k, val in re.findall(r"(\w+)\s*=\s*(\{[^}]*\}|\S+)", line[6:]):
                raw[k] = val.strip("{}")
    values = {}
    while len(values) < len(raw):
        progress = False
        for k, expr in raw.items():
            if k in values:
                continue
            try:
                values[k] = float(eval(expr, {"__builtins__": {}}, dict(values)))
                progress = True
            except NameError:
                pass
        if not progress:
            raise ValueError(f"unresolved subcircuit parameters: {sorted(set(raw) - set(values))}")
    return values


def equation_gate_charge(P, start, end):
    """Gate charge Q(end) - Q(start) from the EPC2204 charge equations (25 C).

    Each state is terminal (VGS, VDS, drain current, gate current). The model's
    gate charge depends only on internal node voltages, so this is the charge
    any correct transient must deliver between the two states.
    """
    sp = lambda x: x + math.log1p(math.exp(-x)) if x > 30 else math.log1p(math.exp(x))
    rs = P["rpara_s_factor"] * P["rpara"]
    rd = (1 - P["rpara_s_factor"]) * P["rpara"]

    def q(vgs_t, vds_t, i_d, i_g):
        vgs = vgs_t - i_g * P["rg_value"] - i_d * rs
        vds = vds_t - i_d * (rs + rd)
        vsd, vgd = -vds, vgs - vds
        q_gs = (P["ags1"] * vgs + 0.5 * P["ags2"] * P["ags4"] * sp((vgs - P["ags3"]) / P["ags4"])
                + P["ags5"] * P["ags7"] * sp((vsd - P["ags6"]) / P["ags7"]))
        q_gd = (P["agd1"] * vgd + 0.5 * P["ags2"] * P["ags4"] * sp((vgd - P["ags3"]) / P["ags4"])
                + P["agd2"] * P["agd4"] * sp((vgd - P["agd3"]) / P["agd4"])
                + P["agd5"] * P["agd7"] * sp((vgd - P["agd6"]) / P["agd7"])
                + P["agd8"] * P["agd10"] * sp((vgd - P["agd9"]) / P["agd10"]))
        return q_gs + q_gd

    return q(*end) - q(*start)


def leakage_charge(P, g, t_end):
    """Charge lost through the model's gate diodes and convergence resistors up to t_end.

    These are the only non-storage paths from the gate in the EPC2204
    subcircuit; their charge grows with test duration, unlike stored charge.
    """
    k = P["aWg"] / 1077 * 0.125
    diode = lambda v: k * (P["dgs1"] * math.expm1(min(v, 10.0) / P["dgs3"])
                           + P["dgs2"] * math.expm1(min(v, 10.0) / P["dgs4"]))
    r_conv = 100000e6 / P["aWg"]
    rs = P["rpara_s_factor"] * P["rpara"]
    rd = (1 - P["rpara_s_factor"]) * P["rpara"]
    t = g["time"]
    leak = []
    for vg, vd, i_d, i_g in zip(g["v(g)"], g["v(d)"], g["ix(x1:drainin)"], g["ix(x1:gatein)"]):
        vgs = vg - i_g * P["rg_value"] - i_d * rs
        vgd = vgs - (vd - i_d * (rs + rd))
        leak.append(diode(vgs) + diode(vgd) + vgs / r_conv + vgd / r_conv)
    q = cumtrapz(t, leak)
    return at(t, q, t_end)


def gate_charge(g, vgs_th):
    """Extract gate-charge quantities and the bench self-checks from one transient."""
    t, vg, vd, idc = g["time"], g["v(g)"], g["v(d)"], g["i(dc)"]
    ig, ipin, idrain = g["i(ig)"], g["ix(x1:gatein)"], g["ix(x1:drainin)"]
    q = cumtrapz(t, ipin)
    tq = lambda x: None if x is None else at(t, q, x)

    def after(x):
        return next(k for k, tt in enumerate(t) if tt >= x) if x is not None else 0

    t_g5 = cross(t, vg, 5.0)
    t_th = cross(t, vg, vgs_th) if vgs_th else None
    t_gs = {f: cross(t, idc, f * LOAD_CURRENT) for f in (0.1, 0.01, 0.001)}
    t_gd = {x: cross(t, vd, x, start=after(t_gs[0.01])) for x in (10.0, 5.0, 1.0)}
    values = {"qg": tq(t_g5), "qg_th": tq(t_th), "qgs": tq(t_gs[0.01])}
    values["qgd"] = (tq(t_gd[5.0]) - values["qgs"]) if t_gd[5.0] is not None and values["qgs"] is not None else None
    k5 = after(t_g5)
    # Coarser integration: every other sample.
    q_half = cumtrapz(t[::2], ipin[::2])
    qg_half = at(t[::2], q_half, t_g5) if t_g5 is not None else None
    residual = [a - b - c / R_HOLD for a, b, c in zip(ig, ipin, vg)]
    checks = {
        "starting_bias": {"vgs_V": vg[0], "vds_V": vd[0], "clamp_current_A": idc[0], "fet_drain_current_A": idrain[0],
                          "expect": "VGS near 0, VDS near 50 V, load current in the clamp, FET off"},
        "gate_current_balance": {
            "definition": "I(Ig) - Ix(X1:gatein) - V(g)/Rhold at every time point",
            "max_abs_residual_A": max(abs(r) for r in residual),
            "hold_resistor_current_at_5V_A": vg[k5] / R_HOLD if t_g5 else None},
        "integration_resolution": {
            "qg_full_C": values["qg"], "qg_every_other_sample_C": qg_half,
            "relative_difference": abs(qg_half - values["qg"]) / values["qg"] if qg_half and values["qg"] else None},
        "drain_transition_at_vgs_5V": {"vds_V": vd[k5], "fet_drain_current_A": idrain[k5], "clamp_current_A": idc[k5],
                                       "expect": "VDS near 16 A x RDS(on), FET carries the 16 A load"},
        "miller_plateau_vgs_V": at(t, vg, t_gs[0.01]) if t_gs[0.01] else None,
        "endpoint_sensitivity": {
            "qgs_C_by_clamp_threshold_fraction": {str(f): tq(x) for f, x in t_gs.items()},
            "qgd_C_by_vds_end_V": {str(x): (tq(tt) - values["qgs"]) if tt is not None and values["qgs"] else None
                                   for x, tt in t_gd.items()}},
    }
    checks["_t_g5"] = t_g5
    checks["_states"] = {"start": (vg[0], vd[0], idrain[0], ipin[0]),
                         "vgs_5V": (vg[k5], vd[k5], idrain[k5], ipin[k5])}
    step = max(1, len(t) // 400)
    curve = {"qg_C": q[:k5 + 1:step], "vgs_V": vg[:k5 + 1:step], "vds_V": vd[:k5 + 1:step]}
    return values, checks, curve


def library_path():
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    entry = next(f for f in sources["files"] if f["name"] == "EPCGaNLibrary.zip")
    archive = VENDOR / "EPCGaNLibrary.zip"
    if not archive.is_file():
        raise SystemExit(f"missing {archive}; download it from {entry['url']} (see devices/epc/sources.json)")
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != entry["sha256"]:
        raise SystemExit(f"{archive} sha256 {digest} does not match the recorded {entry['sha256']}")
    lib = VENDOR / "ltspice" / LIB_NAME
    lib.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as z:
        data = z.read(LIB_NAME)
    if not lib.is_file() or lib.read_bytes() != data:
        lib.write_bytes(data)
    return lib, digest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--executable", default=None)
    parser.add_argument("--output", type=Path, default=ROOT / "results/gan/epc2204-baseline.json")
    parser.add_argument("--curves", type=Path, default=ROOT / "results/gan/epc2204-model-curves.json")
    args = parser.parse_args()
    lib, archive_sha = library_path()
    run_root = ROOT / "runs" / ("epc2204-baseline-" + uuid.uuid4().hex)
    runs, raws = {}, {}
    for name, text in benches().items():
        reltol = RELTOL_OVERRIDES.get(name, RELTOL)
        if reltol is not None:
            text = text.replace("\n.end\n", f"\n.options reltol={reltol:g}\n.end\n")
        r = run_ltspice(text, run_root / name, libraries=[lib], executable=args.executable, timeout_s=600)
        runs[name] = r
        if r.status == "completed" and r.result_path:
            raws[name] = parse_raw(r.result_path)
    failed = {n: r.message for n, r in runs.items() if r.status != "completed"}
    m = {n: r.measurements for n, r in runs.items() if r.status == "completed"}
    v = {}
    notes = {}

    def first(bench, trace):
        values = m.get(bench, {}).get(trace)
        return values[0] if values else None

    for t in (25, 125):
        vd = first(f"rds_on_{t}C", "v(d)")
        v[f"rds_on_{t}C"] = vd / 16 if vd is not None else None
    if "vgs_th" in m:
        vg, ig = m["vgs_th"]["v(g)"], [-x for x in m["vgs_th"]["i(vg)"]]
        v["vgs_th"] = cross(vg, ig, 4e-3)
    vd = first("vsd", "v(d)")
    v["vsd"] = -vd if vd is not None else None
    w = 2 * math.pi * AC_FREQ
    if "caps_gate_ac" in m:
        v["ciss"] = -first("caps_gate_ac", "i(vg)").imag / w
        v["crss"] = first("caps_gate_ac", "i(vd)").imag / w
        notes["capacitance_sign_check"] = "CISS and CRSS use signed currents; a negative value indicates a sign-convention error"
    coss_curve = None
    if "coss_curve_ac" in raws:
        # With one AC frequency per step, LTspice indexes the points by the stepped
        # parameter ("vds") instead of by frequency.
        raw = raws["coss_curve_ac"]
        if raw.axis != "vds":
            raise SystemExit(f"unexpected COSS sweep axis {raw.axis!r}")
        volts = [x.real for x in raw.values["vds"]]
        coss = [-i.imag / w for i in raw.values["i(vd)"]]
        coss_curve = {"vds_V": volts, "coss_F": coss}
        v["coss"] = at(volts, coss, 50.0)
        upto = [k for k, x in enumerate(volts) if x <= BVDSS_HALF + 1e-9]
        vv, cc = [volts[k] for k in upto], [coss[k] for k in upto]
        q = cumtrapz(vv, cc)
        e = cumtrapz(vv, [c * x for c, x in zip(cc, vv)])
        notes["ac_integrated"] = {"qoss_C": q[-1], "eoss_J": e[-1], "points": len(volts),
                                  "method": "trapezoid of small-signal COSS over 0..50 V, 0.25 V spacing"}
    if "qoss_tran" in m:
        t, i, vdv = m["qoss_tran"]["time"], [-x for x in m["qoss_tran"]["i(vd)"]], m["qoss_tran"]["v(d)"]
        end = next(k for k, x in enumerate(t) if x >= 1e-6)
        q = cumtrapz(t[:end + 1], i[:end + 1])[-1]
        e = cumtrapz(t[:end + 1], [a * b for a, b in zip(i, vdv)][:end + 1])[-1]
        v["qoss"] = q
        v["coss_tr"] = q / BVDSS_HALF
        v["coss_er"] = 2 * e / BVDSS_HALF ** 2
        notes["transient"] = {"qoss_C": q, "eoss_J": e, "method": "integral of drain-source current over a 1 us 0 -> 50 V ramp"}
        if "ac_integrated" in notes:
            a = notes["ac_integrated"]
            notes["ac_vs_transient"] = {
                "qoss_relative_difference": abs(a["qoss_C"] - q) / q,
                "eoss_relative_difference": abs(a["eoss_J"] - e) / e,
                "tolerance": 0.02,
                "purpose": "checks that the model's small-signal and large-signal output charge agree in LTspice"}
            notes["ac_vs_transient"]["outcome"] = (
                "pass" if max(notes["ac_vs_transient"]["qoss_relative_difference"],
                              notes["ac_vs_transient"]["eoss_relative_difference"]) <= 0.02 else "fail")
    gate_curve = None
    if "gate_charge_tran" in m:
        values, checks, gate_curve = gate_charge(m["gate_charge_tran"], v.get("vgs_th"))
        v.update(values)
        notes["gate_charge_checks"] = checks
        states = checks.pop("_states")
        t5_nominal = checks.pop("_t_g5")
        P = subckt_params(lib.read_text(encoding="utf-8", errors="replace"))
        q_eq = equation_gate_charge(P, states["start"], states["vgs_5V"])
        notes["gate_charge_equation_check"] = {
            "qg_from_model_equations_C": q_eq, "qg_transient_C": values["qg"],
            "relative_difference": abs(values["qg"] - q_eq) / q_eq, "tolerance": EQUATION_TOLERANCE,
            "outcome": "pass" if abs(values["qg"] - q_eq) / q_eq <= EQUATION_TOLERANCE else "fail",
            "method": ("Q_gate(end) - Q_gate(start) from the EPC2204 charge equations, parameters read from "
                       "the local library, at the simulated start and VGS = 5 V states")}
        conv = {}
        if "gate_charge_tran_reltol1e-7" in m:
            tight, _, _ = gate_charge(m["gate_charge_tran_reltol1e-7"], v.get("vgs_th"))
            tight.pop("_states", None)
            tight.pop("_t_g5", None)
            conv["qg_reltol_1e-7_C"] = tight["qg"]
            conv["relative_change_1e-6_to_1e-7"] = abs(tight["qg"] / values["qg"] - 1)
        if "gate_charge_tran_default_reltol" in m:
            default, _, _ = gate_charge(m["gate_charge_tran_default_reltol"], v.get("vgs_th"))
            conv["qg_default_reltol_C"] = default["qg"]
            conv["default_reltol_note"] = "LTspice default reltol (1e-3); kept to record the under-integration artifact"
        conv["tolerance"] = CONVERGENCE_TOLERANCE
        conv["outcome"] = ("pass" if conv.get("relative_change_1e-6_to_1e-7", 1) <= CONVERGENCE_TOLERANCE else "fail")
