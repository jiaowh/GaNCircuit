AC_FREQ = 1e6  # Hz; Rg = 0.4 ohm makes the series-resistance error ~(w Rg C)^2 < 1e-5
GATE_CURRENT = 10e-3  # A, constant-current gate charge
R_HOLD = 100e3  # ohm, gate hold-down resistor in the gate-charge bench
LOAD_CURRENT = 16.0  # A
HEAD = "* EPC2204 unmodified vendor model; bench generated by scripts/epc2204_baseline.py\n.lib EPCGaNLibrary.lib\n"
# LTspice's default reltol (1e-3) under-integrates the on-state gate charge of this
# model: QG came out 3.8 nC at a 0.1 ns step and 2.5 nC at 0.02 ns. At 1e-6 the
# transient agrees with the model's own charge equations (found 28 September 2026).
RELTOL = 1e-6
RELTOL_OVERRIDES = {"gate_charge_tran_reltol1e-7": 1e-7, "gate_charge_tran_default_reltol": None}
CONVERGENCE_TOLERANCE = 0.005  # relative QG change allowed for reltol 1e-6 -> 1e-7 and for 10 mA -> 2 mA drive
EQUATION_TOLERANCE = 0.01  # relative agreement between transient QG and the model's charge equations


