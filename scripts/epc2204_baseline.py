#!/usr/bin/env python3
"""Run the unmodified EPC2204 LTspice model at datasheet table conditions.

This is the first Stage 1 baseline: vendor model -> LTspice adapter -> parsed
values compared with the datasheet's electrical-characteristics table. The
comparison rules below are fixed before any run:

* limit compliance and deviation from the typical value are reported
  separately; being inside a datasheet limit does not show model accuracy;
* a row is flagged for review when it is outside a datasheet limit or its
  deviation from the typical value exceeds SCREENING_BAND.  The band is a
  screening aid chosen for the first baseline, not an acceptance tolerance.

Datasheet curves are also simulated and stored for the later digitized-curve
comparison. The model is never modified; it is checked against the SHA-256
recorded in devices/epc/sources.json before use.
"""
